const I18n = (function () {
  let lang = localStorage.getItem('otd_lang') || 'en';

  function apply(l) {
    const t = TRANSLATIONS[l] || TRANSLATIONS.en;
    // Text content
    document.querySelectorAll('[data-key]').forEach(el => {
      const v = t[el.dataset.key];
      if (!v) return;
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') el.placeholder = v;
      else el.textContent = v;
    });
    // Placeholders
    document.querySelectorAll('[data-key-ph]').forEach(el => {
      const v = t[el.dataset.keyPh];
      if (v) el.placeholder = v;
    });
    // Direction
    const rtl = l === 'ar';
    document.documentElement.setAttribute('lang', l);
    document.documentElement.setAttribute('dir', rtl ? 'rtl' : 'ltr');
    document.body.setAttribute('dir', rtl ? 'rtl' : 'ltr');
    // Lang button
    const btn = document.getElementById('lang-btn');
    if (btn) btn.textContent = rtl ? 'EN' : 'AR';
    lang = l;
    localStorage.setItem('otd_lang', l);
  }

  return {
    init() { apply(lang); },
    toggle() { apply(lang === 'en' ? 'ar' : 'en'); },
    t(key) { return (TRANSLATIONS[lang] || TRANSLATIONS.en)[key] || key; },
    get current() { return lang; }
  };
})();

document.addEventListener('DOMContentLoaded', () => {
  I18n.init();
  document.getElementById('lang-btn')?.addEventListener('click', () => I18n.toggle());
});
